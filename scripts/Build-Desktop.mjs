import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { packSource } from '../desktop/releases/0.2.1-rc.3.1/Reproduce.mjs';
import { sha256, installation } from '../desktop/official-runtime.mjs';
const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'sources/dsh-desktop-compat');
if (!process.argv[2] || !process.argv[3]) throw Error('Usage: node scripts/Build-Desktop.mjs <new-output-directory> <official-app.asar>');
const output = path.resolve(process.argv[2]), archive = path.resolve(process.argv[3]);
const release = JSON.parse(fs.readFileSync(path.join(root, 'desktop/releases/0.2.1-rc.3.1/manifest.json')));
if (sha256(fs.readFileSync(archive)) !== release.official.windowsX64.appAsarSha256) throw Error('Exact official rc.3 ASAR required');
if (fs.existsSync(output) && fs.readdirSync(output).length) throw Error('Output must be new or empty');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'package.json')));
const expected = release.packages.find(row => row.name === manifest.name);
const bytes = packSource(source);
if (manifest.version !== expected.version || sha256(bytes) !== expected.sha256) throw Error('Source differs from accepted rc.3 package');
fs.mkdirSync(output, { recursive: true });
const target = path.join(output, `${manifest.name}-${manifest.version}.tgz`);
if (fs.existsSync(target) && !fs.readFileSync(target).equals(bytes)) throw Error('Fixed candidate exists with different bytes; choose a new version');
fs.writeFileSync(target, bytes);
const evidence = { package: manifest.name, version: manifest.version, archive: { path: path.basename(target), sha256: sha256(bytes), bytes: bytes.length },
  official: installation(archive), reproducible: true };
fs.writeFileSync(path.join(output, 'candidate-manifest.json'), `${JSON.stringify(evidence, null, 2)}\n`);
console.log(JSON.stringify(evidence, null, 2));
