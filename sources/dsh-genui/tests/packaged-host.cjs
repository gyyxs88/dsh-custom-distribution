// ELECTRON_RUN_AS_NODE=1 "D:/DSH/DeepSeek Harness.exe" tests/packaged-host.cjs <unpacked-package>
// Uses the installed official rc.2 registry and Cordis, without a provider/session.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { createRequire } = require('node:module')
const official = createRequire('D:/DSH/resources/app.asar/dsh/package.json')
const { Context } = official('@deepseek-ai/cordis')
const { SkillRegistry } = official('@deepseek-ai/dsh-skill')
const { SystemPrompt } = official('@deepseek-ai/dsh-system-prompt')
const { ToolRuntime } = official('@deepseek-ai/dsh-tools')
const root = path.resolve(process.argv[2])
const genui = require(path.join(root, 'lib/index.js'))
const rawSkill = fs.readFileSync(path.join(root, 'SKILL.md'), 'utf8').replaceAll('\r\n', '\n')
const body = rawSkill.replace(/^---\n[\s\S]*?\n---\n/, '').trim()
async function check(ctx) {
  const catalog = await ctx.skills.list()
  assert.equal(catalog.filter(s => s.name === 'genui').length, 1)
  const skill = await ctx.skills.get('genui')
  assert.equal(skill.content, body)
  assert.equal(skill.path, path.join(root, 'SKILL.md'))
  assert.deepEqual(skill.invocation, { modelInvocable: true, userInvocable: true })
}
async function main() {
  for (const order of ['early', 'late']) {
    const ctx = new Context()
    const prompt = await ctx.plugin(SystemPrompt)
    let registry
    let runtime
    if (order === 'early') registry = await ctx.plugin(SkillRegistry)
    if (order === 'early') runtime = await ctx.plugin(ToolRuntime)
    const plugin = await ctx.plugin(genui)
    if (order === 'late') registry = await ctx.plugin(SkillRegistry)
    if (order === 'late') runtime = await ctx.plugin(ToolRuntime)
    await check(ctx)
    assert.deepEqual(ctx.tools.schemas().map(t => t.name).sort(), ['render_ui', 'validate_dsh_ui'])
    const validator = ctx.tools.get('validate_dsh_ui')
    const failing = await validator.execute({ spec: { items: [{ type: 'callout', content: 42 }] } })
    assert.match(failing, /\$\.items\[0\]\.content \(callout\)/)
    // Service replacement: registration must appear exactly once again.
    await registry.dispose()
    registry = await ctx.plugin(SkillRegistry)
    await check(ctx)
    await plugin.dispose()
    assert.equal(ctx.tools.schemas().length, 0)
    assert.equal((await ctx.skills.list()).some(s => s.name === 'genui'), false)
    const reload = await ctx.plugin(genui)
    await check(ctx)
    await reload.dispose()
    assert.equal((await ctx.skills.list()).length, 0)
    await registry.dispose()
    await runtime.dispose()
    await prompt.dispose()
    console.log(`PASS official registry/tools ${order}: catalog/body/schema/field diagnostics/service replacement/disposal/reload`)
  }
  const ctx = new Context()
  const prompt = await ctx.plugin(SystemPrompt)
  const plugin = await ctx.plugin(genui)
  assert.equal(ctx.reflect.get('skills', false), undefined)
  await plugin.dispose()
  await prompt.dispose()
  console.log('PASS optional skills/tools/webServer absent')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
